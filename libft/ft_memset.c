#include <stddef.h>

void	*ft_memset(void *s, int c, size_t n)
{
	size_t	i;
	char	*tmp;

	tmp = (char *) s;
	i = 0;
	while (i < n)
	{
		tmp[i++] = c;
	}
	return ((void *) tmp);
}
